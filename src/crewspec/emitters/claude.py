"""Emitter that renders a crewspec into Claude-compatible artifacts.

The Claude target is a self-contained *skills-directory plugin*: everything lands
under a single ``<dest>/.claude/skills/crewspec/`` directory that crewspec owns.
Because that directory carries a ``.claude-plugin/plugin.json`` manifest, Claude
Code auto-discovers it as the ``crewspec@skills-dir`` plugin on the next session,
with no marketplace and no install step. Owning one namespace lets re-emission
wipe and regenerate freely without ever touching the user's own ``.claude/`` files.

All Claude-specific frontmatter and schema knowledge lives here so a sibling
emitter can reuse :class:`~crewspec.emitters.base.Emitter` untouched.
"""

from __future__ import annotations

import json
import shutil
import warnings
from pathlib import Path

import yaml

from crewspec.emitters.base import Emitter
from crewspec.emitters.errors import MissingPersonaDescription
from crewspec.ir import ResolvedAgent, ResolvedIR, ResolvedMcp, ResolvedSkill
from crewspec.models.interpolate import EnvRef, parse_refs
from crewspec.models.mcp import McpServer, StdioMcpServer

#: VCS/OS cruft never worth copying into a skill's emitted tree. ``.git`` in
#: particular can be enormous and would embed a nested repo in the plugin.
_SKILL_COPY_IGNORE = shutil.ignore_patterns(".git", "__pycache__", "*.pyc", ".DS_Store")


class ClaudeEmitter(Emitter):
    """Render the crewspec IR into a Claude Code plugin under ``dest``."""

    name = "claude"

    #: Plugin directory, relative to ``dest``. crewspec owns this subtree.
    plugin_path = (".claude", "skills", "crewspec")
    #: The plugin's ``name`` (and namespace) in its ``plugin.json`` manifest.
    plugin_name = "crewspec"

    def output_path(self, dest: Path) -> Path:
        """The plugin root under ``dest`` that crewspec owns and writes into."""
        return dest.joinpath(*self.plugin_path)

    def emit(self, ir: ResolvedIR, dest: Path) -> None:
        plugin_root = self.output_path(dest)

        # crewspec owns this subtree: wipe and regenerate so re-emission is
        # byte-identical and never leaves a stale agent/skill behind.
        if plugin_root.exists():
            shutil.rmtree(plugin_root)
        plugin_root.mkdir(parents=True)

        self._write_manifest(plugin_root)
        for agent in ir.agents:
            self._write_agent(plugin_root, agent)
        self._copy_skills(plugin_root, ir.agents)
        self._write_mcp(plugin_root, ir.mcps)

    def _write_manifest(self, plugin_root: Path) -> None:
        manifest = {"name": self.plugin_name, "description": "Generated by crewspec."}
        path = plugin_root / ".claude-plugin" / "plugin.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(manifest, indent=2) + "\n")

    def _write_agent(self, plugin_root: Path, agent: ResolvedAgent) -> None:
        description, body = self._read_persona(agent)

        # Field order is fixed for stable, scannable output. ``mcpServers`` is
        # deliberately absent: plugin-shipped agents may not declare it, so MCP
        # scoping lives in the plugin's shared .mcp.json instead.
        frontmatter: dict[str, str] = {"name": agent.name, "description": description}
        tools = self._tools_field(agent)
        if tools is not None:
            frontmatter["tools"] = tools
        if agent.skills:
            frontmatter["skills"] = ", ".join(skill.name for skill in agent.skills)

        block = yaml.safe_dump(
            frontmatter, sort_keys=False, allow_unicode=True, width=1000
        )
        text = f"---\n{block}---\n\n" + body.lstrip("\n")

        path = plugin_root / "agents" / f"{agent.name}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

    def _tools_field(self, agent: ResolvedAgent) -> str | None:
        """The ``tools`` allowlist, or ``None`` to inherit all tools.

        An empty ``allowed_tools`` means "no restriction" — omit the field so
        the agent inherits every built-in tool plus the plugin's MCP tools. A
        non-empty list becomes an allowlist, so each granted MCP is appended as
        ``mcp__<server>`` to keep it reachable past the allowlist.
        """

        if not agent.tools:
            return None
        granted = [f"mcp__{mcp.name}" for mcp in agent.mcps]
        return ", ".join((*agent.tools, *granted))

    def _read_persona(self, agent: ResolvedAgent) -> tuple[str, str]:
        text = agent.persona_path.read_text()
        meta, body = _split_frontmatter(text)
        description = meta.get("description") if meta else None
        if not isinstance(description, str) or not description:
            raise MissingPersonaDescription(agent.name, agent.persona_path)
        return description, body

    def _copy_skills(
        self, plugin_root: Path, agents: tuple[ResolvedAgent, ...]
    ) -> None:
        # Each skill is copied once; the same skill may be shared across agents.
        skills: dict[str, ResolvedSkill] = {}
        for agent in agents:
            for skill in agent.skills:
                skills.setdefault(skill.name, skill)

        for skill in skills.values():
            dest_dir = plugin_root / "skills" / skill.name
            # A skill *is* its directory: copy the whole tree so nothing the
            # SKILL.md references (reference docs, scripts, data, fonts, a
            # LICENSE, ...) is left behind — only VCS/OS junk is dropped.
            # plugin_root was just wiped, so dest_dir cannot pre-exist.
            shutil.copytree(skill.path, dest_dir, ignore=_SKILL_COPY_IGNORE)
            _normalize_skill_md(dest_dir)

    def _write_mcp(self, plugin_root: Path, mcps: tuple[ResolvedMcp, ...]) -> None:
        if not mcps:
            return

        file_secrets: set[str] = set()
        servers = {mcp.name: _server_dict(mcp.server, file_secrets) for mcp in mcps}
        for target in sorted(file_secrets):
            warnings.warn(
                f"file secret '${{file:{target}}}' has no .mcp.json equivalent; "
                f"it is written verbatim and will not resolve until a launcher "
                f"mounts it",
                stacklevel=2,
            )

        path = plugin_root / ".mcp.json"
        path.write_text(json.dumps({"mcpServers": servers}, indent=2) + "\n")


def _normalize_skill_md(skill_dir: Path) -> None:
    """Rename a case-variant ``skill.md`` to the canonical ``SKILL.md``.

    crewspec resolves skills case-insensitively on macOS, so a source skill may
    carry a lowercase ``skill.md``. A case-sensitive host (Linux CI, a cloned
    repo) needs the exact name, so normalise it on emit to keep the plugin
    portable. A dir that already has ``SKILL.md`` is left untouched.
    """

    canonical = skill_dir / "SKILL.md"
    for child in skill_dir.iterdir():
        if child.name != "SKILL.md" and child.name.lower() == "skill.md":
            child.rename(canonical)
            return


def _split_frontmatter(text: str) -> tuple[dict[str, object] | None, str]:
    """Split leading ``---``-fenced YAML frontmatter from the markdown body.

    Returns ``(None, text)`` when no well-formed frontmatter block is present;
    the caller treats a missing block as a missing ``description``.
    """

    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None, text

    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            block = "\n".join(lines[1:index])
            body = "\n".join(lines[index + 1 :])
            try:
                meta = yaml.safe_load(block)
            except yaml.YAMLError:
                return None, text
            if not isinstance(meta, dict):
                return None, text
            return meta, body

    return None, text


def _server_dict(server: McpServer, file_secrets: set[str]) -> dict[str, object]:
    """Render one MCP server into its Claude ``.mcp.json`` mapping.

    ``${...}`` references are rendered by kind (see :func:`_render_value`):
    env refs survive verbatim for Claude to expand, ``${secret:NAME}`` collapses
    to ``${NAME}``, and ``${file:PATH}`` is recorded in ``file_secrets``.
    """

    if isinstance(server, StdioMcpServer):
        data: dict[str, object] = {
            "type": server.type,
            "command": _render_value(server.command, file_secrets),
        }
        if server.args:
            data["args"] = [_render_value(arg, file_secrets) for arg in server.args]
        if server.env:
            data["env"] = {
                key: _render_value(value, file_secrets)
                for key, value in server.env.items()
            }
        return data

    # HttpMcpServer | SseMcpServer — both carry url + headers.
    remote: dict[str, object] = {
        "type": server.type,
        "url": _render_value(server.url, file_secrets),
    }
    if server.headers:
        remote["headers"] = {
            key: _render_value(value, file_secrets)
            for key, value in server.headers.items()
        }
    return remote


def _render_value(value: str, file_secrets: set[str]) -> str:
    """Rewrite ``${...}`` references for the Claude ``.mcp.json`` target.

    * ``${VAR}`` / ``${VAR:-default}`` (env) — kept verbatim; Claude Code expands
      them natively at runtime.
    * ``${secret:NAME}`` — rewritten to ``${NAME}`` so only the name lands in the
      file and Claude expands it from the runtime environment.
    * ``${file:PATH}`` — left verbatim and its target recorded so the caller can
      warn; Claude has no file-mount equivalent without a launcher.
    """

    out: list[str] = []
    for fragment in parse_refs(value):
        if isinstance(fragment, str):
            out.append(fragment)
        elif isinstance(fragment, EnvRef):
            if fragment.default is not None:
                out.append(f"${{{fragment.name}:-{fragment.default}}}")
            else:
                out.append(f"${{{fragment.name}}}")
        elif fragment.kind == "secret":
            out.append(f"${{{fragment.target}}}")
        else:
            file_secrets.add(fragment.target)
            out.append(f"${{file:{fragment.target}}}")
    return "".join(out)
